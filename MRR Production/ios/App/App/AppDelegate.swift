    // Required by @capacitor/push-notifications: these two overrides are the
    // plugin's documented integration point. APNs hands the raw device token
    // (or an error) to the OS-level delegate methods below, not to anything in
    // the WKWebView bridge directly — forwarding them through NotificationCenter
    // is how the JS-side PushNotifications.addListener("registration"/
    // "registrationError") calls in src/shared/utils/pushRegistration.js
    // actually receive them.
    //
    // There is deliberately no didReceiveRemoteNotification override here. A
    // third one used to forward silent/background pushes via
    // .capacitorDidReceiveRemoteNotification, but that Notification.Name is not
    // declared anywhere in the installed Capacitor packages (only the two below
    // are, in @capacitor/ios's CAPNotifications.swift) — it does not compile,
    // and nothing on the JS side listens for it. Add it back only alongside
    // whatever JS listener would actually consume it.
    func application(_ application: UIApplication, didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        NotificationCenter.default.post(name: .capacitorDidRegisterForRemoteNotifications, object: deviceToken)
    }

    func application(_ application: UIApplication, didFailToRegisterForRemoteNotificationsWithError error: Error) {
        NotificationCenter.default.post(name: .capacitorDidFailToRegisterForRemoteNotifications, object: error)
    }

    func application(_ application: UIApplication,
                     configurationForConnecting connectingSceneSession: UISceneSession,
                     options: UIScene.ConnectionOptions) -> UISceneConfiguration {
        let config = UISceneConfiguration(name: "Default Configuration",
                                          sessionRole: connectingSceneSession.role)
        config.delegateClass = SceneDelegate.self
        return config
    }
